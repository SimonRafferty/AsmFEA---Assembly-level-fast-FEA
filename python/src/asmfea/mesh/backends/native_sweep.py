"""native_sweep: our own swept meshes of thin-walled regions (milestone 4, D6 option A).

Two modes, both one quadratic wedge (C3D15) layer per sweep step:

- section: a member clean span. The planar section at the span's start is meshed in 2D
  (second-order triangles, about one through the wall) and swept along the member axis in
  layers (M0: within 0.04 % of beam theory, 1-2 % in local wall bending).
- skin: a constant-thickness wall (sheet, bent sheet, hollow-section end region). The faces
  are paired across the thickness by ray casting; one skin is meshed in 2D and every node
  is offset through the thickness onto the other skin, one wedge through the wall.

The 2D meshes come from the Gmsh executable driven by a .geo script (Change 001: a
separate process exchanging files; Gmsh is never imported). Everything else is our code.
A region that is not prismatic (section) or not of constant thickness (skin) is refused
with a reason, and the mesher chain falls back to tets. The worker also refuses a swept
mesh whose boundary does not land on the CAD faces (face tagging), so a wrong guess about
the shape can never reach the solver.
"""
from __future__ import annotations

import math
from pathlib import Path
from typing import Callable, Optional

import numpy as np

from ... import defaults
from ..msh import read_msh22
from . import MeshRequest, MeshResult, finish_blocks, save_neutral
from .gmsh_cli import GmshCliBackend, run_logged


class SweepRefused(Exception):
    """The region does not have the shape this sweep needs."""


class NativeSweepBackend:
    name = "native_sweep"

    def __init__(self, gmsh_exe: Optional[str] = None):
        self.gmsh = GmshCliBackend(gmsh_exe)

    def available(self) -> bool:
        return self.gmsh.available()          # 2D meshes come from the Gmsh executable

    def version(self) -> str:
        return f"asmfea-sweep-2/gmsh-{self.gmsh.version()}"

    def mesh(self, req: MeshRequest, on_line: Callable[[str], None] = lambda s: None) -> MeshResult:
        from ...geometry import read_step
        out_dir = Path(req.out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        log_path = out_dir / "sweep.log"
        mode = req.extra.get("mode")
        try:
            solid = read_step(Path(req.geometry_file))[req.body_selector]
            if mode == "section":
                X, blocks, t, info = section_sweep(solid, req, self._mesh2d(out_dir, log_path, req, on_line))
            elif mode == "skin":
                X, blocks, t, info = skin_sweep(solid, req, self._mesh2d(out_dir, log_path, req, on_line))
            else:
                raise SweepRefused(f"unknown sweep mode {mode!r}")
        except SweepRefused as e:
            with open(log_path, "a", encoding="utf-8") as lg:
                lg.write(f"refused: {e}\n")
            return MeshResult(False, self.name, error=f"{mode} sweep refused: {e}", log_path=log_path)
        Xp = np.vstack([np.zeros((1, 3)), X])
        blocks, quality = finish_blocks(Xp, blocks)
        if quality["inverted"]:
            return MeshResult(False, self.name, log_path=log_path,
                              error=f"{mode} sweep: {quality['inverted']} inverted wedges")
        quality.update(info)
        out = out_dir / "mesh.npz"
        save_neutral(out, X, blocks)
        return MeshResult(True, self.name, mesh_file=out, nodes=len(X), elements=sum(len(c) for _, c in blocks),
                          quality=quality, log_path=log_path,
                          surface_tolerance=max(1e-3, defaults.SWEEP_SURFACE_TOL_T * t))

    def _mesh2d(self, out_dir: Path, log_path: Path, req: MeshRequest, on_line):
        """A function (shape, size) -> (X (n, 3), tri6 (m, 6) 0-based, gmsh order)."""
        def mesh2d(shape, size: float):
            from ...geometry import write_step
            step = out_dir / "surface.step"
            write_step(step, [shape])
            geo, msh = out_dir / "surface.geo", out_dir / "surface.msh"
            geo.write_text("\n".join([
                "// generated by asmfea native_sweep: 2D mesh to sweep",
                'SetFactory("OpenCASCADE");',
                'Geometry.OCCTargetUnit = "MM";',
                f's() = ShapeFromFile("{step.resolve().as_posix()}");',
                f"Mesh.MeshSizeMax = {size:.9g};",
                f"Mesh.MeshSizeMin = {size * defaults.MESH_SIZE_MIN_FRACTION:.9g};",
                f"Mesh.MeshSizeFromCurvature = {defaults.MESH_CURVATURE_POINTS};",
                "Mesh.Algorithm = 6;",            # Frontal-Delaunay 2D
                "Mesh.ElementOrder = 2;",
                "Mesh.MshFileVersion = 2.2;",
                "Mesh.Binary = 0;",
                "General.NumThreads = 1;",
                ""]))
            code, timed_out, tail = run_logged([self.gmsh.exe, str(geo), "-2", "-format", "msh22", "-o", str(msh),
                                                "-nt", "1", "-v", "4"], out_dir, log_path, req.timeout_s, on_line)
            if timed_out:
                raise SweepRefused(f"2D mesh timed out after {req.timeout_s:.0f} s")
            errs = [l for l in tail if l.startswith("Error")]
            if code != 0 or errs or not msh.exists():
                raise SweepRefused("2D mesh failed: " + (errs[0] if errs else f"exit code {code}"))
            ids, coords, elems = read_msh22(msh)
            if 9 not in elems:
                raise SweepRefused("2D mesh has no second-order triangles")
            used = np.unique(elems[9])
            pos = {int(n): i for i, n in enumerate(ids)}
            X = coords[[pos[int(n)] for n in used]]
            remap = {int(n): i for i, n in enumerate(used)}
            tri = np.vectorize(remap.__getitem__)(elems[9])
            return X, tri
        return mesh2d


# --------------------------------------------------------------------------- #
# Wedges from a tri6 layer

def _wedges(tri: np.ndarray, bottom: np.ndarray, top: np.ndarray, mid: np.ndarray) -> np.ndarray:
    """C3D15 rows (0-based node indices) from tri6 (gmsh order: corners, then midsides 01, 12,
    20) given index maps for the bottom layer, the top layer and the mid layer (corners only).
    CalculiX order: bottom corners, top corners, bottom midsides, top midsides, verticals."""
    a, b, c, ab, bc, ca = tri.T
    return np.stack([bottom[a], bottom[b], bottom[c], top[a], top[b], top[c],
                     bottom[ab], bottom[bc], bottom[ca], top[ab], top[bc], top[ca],
                     mid[a], mid[b], mid[c]], axis=1)


def _layered(X2: np.ndarray, tri: np.ndarray, offsets: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Stack layers of the 2D mesh. offsets (n_planes, n, 3): position shift of every 2D node
    on each node plane; even planes carry every node, odd (mid) planes the corners only.
    Returns (X, C3D15 conn with local ids from 1)."""
    n = len(X2)
    corners = np.unique(tri[:, :3])
    nplanes = offsets.shape[0]
    X, idx = [], []
    count = 0
    for k in range(nplanes):
        m = np.full(n, -1, dtype=np.int64)
        sel = np.arange(n) if k % 2 == 0 else corners
        m[sel] = np.arange(count, count + len(sel))
        count += len(sel)
        X.append(X2[sel] + offsets[k][sel])
        idx.append(m)
    rows = [_wedges(tri, idx[2 * j], idx[2 * j + 2], idx[2 * j + 1]) for j in range((nplanes - 1) // 2)]
    return np.vstack(X), np.vstack(rows) + 1


# --------------------------------------------------------------------------- #
# section: member clean span

def section_sweep(solid, req: MeshRequest, mesh2d) -> tuple[np.ndarray, list, float, dict]:
    """Sweep the section at s0 along the member path (straight: translated; arc: rotated about
    the arc's axis) to s1 in layers of SWEEP_LAYER_T x wall, measured along the path."""
    from ...geometry import MemberPath, part_faces
    e = req.extra
    path = MemberPath(e)
    s0, s1 = float(e["s0"]), float(e["s1"])
    L = s1 - s0
    if L <= 0:
        raise SweepRefused("empty span")
    faces = part_faces(solid)
    tol = max(1e-6 * L, 1e-4)
    t0 = path.tangent(s0)
    start = [f for f in faces if f.surface == "plane" and abs(abs(np.dot(f.normal, t0)) - 1) < 1e-9
             and abs(path.s_of(f.centroid) - s0) < tol]
    if len(start) != 1:
        raise SweepRefused(f"{len(start)} section faces at the span start (expected 1)")
    sec = start[0]
    # wall thickness: given, or from the section (thin wall: area ~ perimeter_total * t / 2)
    t = e.get("wall")
    if not t:
        from OCP.BRepGProp import BRepGProp
        from OCP.GProp import GProp_GProps
        g = GProp_GProps()
        BRepGProp.LinearProperties_s(sec.shape, g)
        t = 2.0 * sec.area / g.Mass()
    factor = float(e.get("factor", 1.0))
    size2d = float(e.get("section_t", defaults.SWEEP_SECTION_T)) * t * factor     # a fast run sets its own
    layer = float(e.get("layer_t", defaults.SWEEP_LAYER_T)) * t * factor
    X2, tri = mesh2d(sec.shape, size2d)
    # every 2D node must lie on the section plane at s0
    if np.abs((X2 - path.point(s0)) @ t0).max() > tol:
        raise SweepRefused("section mesh is not planar")
    nl = max(1, math.ceil(L / layer))
    offsets = np.stack([path.move(X2, s0, s) - X2 for s in np.linspace(s0, s1, 2 * nl + 1)])
    X, conn = _layered(X2, tri, offsets)
    return X, [("C3D15", conn)], float(t), {"mode": "section", "wall": float(t), "layers": nl,
                                           "path": path.kind, "section_triangles": int(len(tri))}


# --------------------------------------------------------------------------- #
# skin: constant-thickness wall

def _face_sample(face) -> tuple[np.ndarray, np.ndarray]:
    """(point on the face, outward unit normal there): the centre of the face's largest
    triangle in a coarse triangulation, evaluated on the surface, so it lies on the face."""
    from OCP.BRep import BRep_Tool
    from OCP.BRepAdaptor import BRepAdaptor_Surface
    from OCP.BRepMesh import BRepMesh_IncrementalMesh
    from OCP.TopLoc import TopLoc_Location
    from ...geometry import _point_normal
    loc = TopLoc_Location()
    tri = BRep_Tool.Triangulation_s(face, loc)
    if tri is None:
        BRepMesh_IncrementalMesh(face, 0.5, False, 0.5, True)
        tri = BRep_Tool.Triangulation_s(face, loc)
    if tri is None or tri.NbTriangles() == 0 or not tri.HasUVNodes():
        raise SweepRefused("a face could not be sampled")
    best, uv = -1.0, None
    for i in range(1, tri.NbTriangles() + 1):
        n1, n2, n3 = tri.Triangle(i).Get()
        P = [tri.Node(k) for k in (n1, n2, n3)]
        a = np.linalg.norm(np.cross(np.array([P[1].X() - P[0].X(), P[1].Y() - P[0].Y(), P[1].Z() - P[0].Z()]),
                                    np.array([P[2].X() - P[0].X(), P[2].Y() - P[0].Y(), P[2].Z() - P[0].Z()])))
        if a > best:
            U = [tri.UVNode(k) for k in (n1, n2, n3)]
            best, uv = a, (sum(q.X() for q in U) / 3, sum(q.Y() for q in U) / 3)
    p, n = _point_normal(face, BRepAdaptor_Surface(face), *uv)
    return p, n


def _ray(intersector, p: np.ndarray, d: np.ndarray, eps: float):
    """(distance, hit face) of the first boundary crossing from p along d, or (inf, None)."""
    from OCP.gp import gp_Dir, gp_Lin, gp_Pnt
    intersector.Perform(gp_Lin(gp_Pnt(*p), gp_Dir(*d)), eps, 1e12)
    best, face = math.inf, None
    for i in range(1, intersector.NbPnt() + 1):
        w = intersector.WParameter(i)
        if eps < w < best:
            best, face = w, intersector.Face(i)
    return best, face


SIDE_WALL_COS = 0.3   # a face at more than ~73 degrees to the skin it meets is a side wall


def pair_skins(solid, expected_t: Optional[float] = None):
    """Split the faces of a constant-thickness solid into skin A, skin B and side faces.

    Returns (faces, A, B, t): FaceInfo list and index lists. Refuses when the wall
    thickness is not one constant value.
    """
    from OCP.IntCurvesFace import IntCurvesFace_ShapeIntersector
    from OCP.TopAbs import TopAbs_EDGE
    from OCP.TopExp import TopExp
    from ...geometry import part_faces
    faces = part_faces(solid)
    if len(faces) < 3:
        raise SweepRefused("too few faces")
    ix = IntCurvesFace_ShapeIntersector()
    ix.Load(solid, 1e-7)
    hit, dist, normal = [], [], []
    for f in faces:
        p, n = _face_sample(f.shape)
        d, h = _ray(ix, p, -n, 1e-6)
        j = next((g.index for g in faces if h is not None and g.shape.IsSame(h)), None)
        hit.append(j)
        dist.append(d)
        normal.append(np.asarray(n, float))
    dist = np.asarray(dist)
    big = int(np.argmax([f.area for f in faces]))
    t = expected_t or float(dist[big])
    if not np.isfinite(t) or t <= 0:
        raise SweepRefused("no wall thickness found")
    if abs(dist[big] - t) > defaults.SKIN_THICKNESS_RTOL * t:
        raise SweepRefused(f"largest face is {dist[big]:.4g} thick, expected {t:.4g}")
    if np.sqrt(faces[big].area) < defaults.SKIN_MIN_ASPECT * t:
        raise SweepRefused(f"not a thin wall: {t:.4g} thick against a largest face about {np.sqrt(faces[big].area):.4g} across")
    from ...geometry import _IndexedShapeMap, subshapes
    emap = _IndexedShapeMap()
    TopExp.MapShapes_s(solid, TopAbs_EDGE, emap)
    edges_of = [{emap.FindIndex(e) for e in subshapes(f.shape, TopAbs_EDGE)} for f in faces]
    skin = {f.index for f, d in zip(faces, dist) if abs(d - t) <= defaults.SKIN_THICKNESS_RTOL * t}
    for f, d in zip(faces, dist):
        if f.index in skin or d >= defaults.SKIN_SIDE_FACTOR * t:
            continue
        # A side wall (perpendicular to the skins it meets) fires its ray along the sheet, across the
        # material beside it: a narrow strip by a small cut-out or corner radius measures the strip's
        # width, not the wall thickness (found live: 3 mm sheet parts refused at 1.5 mm).
        side = any(abs(float(np.dot(normal[f.index], normal[g]))) < SIDE_WALL_COS
                   for g in skin if edges_of[g] & edges_of[f.index])
        if not side:
            raise SweepRefused(f"wall thickness varies: face {f.index} is {d:.4g} thick against {t:.4g}")
    # skin A: the faces connected to the largest one through shared edges, skins only

    def neighbours(f):
        return {g.index for g in faces if g.index != f.index and edges_of[g.index] & edges_of[f.index]}
    A, stack = {big}, [big]
    while stack:
        for j in neighbours(faces[stack.pop()]):
            if j in skin and j not in A:
                A.add(j)
                stack.append(j)
    B = skin - A
    if not B:
        raise SweepRefused("no opposite skin")
    if any(hit[i] not in B for i in A) or any(hit[i] not in A for i in B):
        raise SweepRefused("skins are not paired face to face")
    return faces, sorted(A), sorted(B), float(t)


def _inward_normals(faces, A: list[int], P: np.ndarray, tol: float) -> list[list[np.ndarray]]:
    """For each point, the inward unit normals of the skin-A faces it lies on."""
    from ..tagging import _surface_distance
    out = [[] for _ in range(len(P))]
    for i in A:
        f = faces[i]
        lo, hi = np.asarray(f.bbox[:3]) - 10 * tol, np.asarray(f.bbox[3:]) + 10 * tol
        cand = np.nonzero(np.all((P >= lo) & (P <= hi), axis=1))[0]
        if not len(cand):
            continue
        on = cand[_surface_distance(f, P[cand]) <= tol]
        if not len(on):
            continue
        if f.surface == "plane":
            N = np.repeat(-np.asarray(f.normal, float)[None, :], len(on), axis=0)
        elif f.surface == "cylinder":
            a, c = np.asarray(f.axis), np.asarray(f.axis_point)
            r = P[on] - c
            r = r - np.outer(r @ a, a)
            r /= np.linalg.norm(r, axis=1)[:, None]
            N = -r if f.convex else r
        else:
            from OCP.BRep import BRep_Tool
            from OCP.BRepAdaptor import BRepAdaptor_Surface
            from OCP.GeomAPI import GeomAPI_ProjectPointOnSurf
            from OCP.gp import gp_Pnt
            from ...geometry import _point_normal
            surf, ad = BRep_Tool.Surface_s(f.shape), BRepAdaptor_Surface(f.shape)
            N = []
            for k in on:
                pr = GeomAPI_ProjectPointOnSurf(gp_Pnt(*P[k]), surf)
                u, v = pr.LowerDistanceParameters()
                N.append(-_point_normal(f.shape, ad, u, v)[1])
            N = np.asarray(N)
        for k, n in zip(on, N):
            out[k].append(n)
    return out


def _offset(normals: list[np.ndarray], t: float) -> Optional[np.ndarray]:
    """The shift v with v . n = t for every (distinct) normal: the corner of the offset faces."""
    uniq = []
    for n in normals:
        if not any(np.dot(n, m) > 1 - 1e-9 for m in uniq):
            uniq.append(n)
    if not uniq:
        return None
    if len(uniq) == 1:
        return t * uniq[0]
    N = np.asarray(uniq)
    v, *_ = np.linalg.lstsq(N, np.full(len(uniq), t), rcond=None)
    return v


def skin_sweep(solid, req: MeshRequest, mesh2d) -> tuple[np.ndarray, list, float, dict]:
    from OCP.BRep import BRep_Builder
    from OCP.TopoDS import TopoDS_Shell
    e = req.extra
    faces, A, B, t = pair_skins(solid, e.get("thickness"))
    factor = float(e.get("factor", 1.0))
    size2d = min(defaults.SKIN_SIZE_T * t * factor, req.size_max if e.get("cap_size") else math.inf)
    shell = TopoDS_Shell()
    bld = BRep_Builder()
    bld.MakeShell(shell)
    for i in A:
        bld.Add(shell, faces[i].shape)
    X2, tri = mesh2d(shell, size2d)
    tol = max(1e-3, defaults.SWEEP_SURFACE_TOL_T * t)
    normals = _inward_normals(faces, A, X2, tol)
    V = np.zeros_like(X2)
    for k, ns in enumerate(normals):
        v = _offset(ns, t)
        if v is None:
            raise SweepRefused("a skin node lies on no skin face")
        if np.linalg.norm(v) > 3 * t:
            raise SweepRefused("a skin corner is too sharp to offset")
        V[k] = v
    offsets = np.stack([np.zeros_like(X2), 0.5 * V, V])
    X, conn = _layered(X2, tri, offsets)
    return X, [("C3D15", conn)], float(t), {"mode": "skin", "thickness": t, "skin_faces": len(A),
                                           "side_faces": len(faces) - len(A) - len(B),
                                           "skin_triangles": int(len(tri))}

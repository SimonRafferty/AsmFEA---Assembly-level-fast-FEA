"""gmsh_cli: the Gmsh executable driven by a generated .geo script (Change 001).

Gmsh is GPL; it runs only as a separate process that exchanges files. Nothing here
imports or loads the Gmsh library.

Script and command line, checked against the Gmsh 4.15 reference manual:
  SetFactory("OpenCASCADE");  v() = ShapeFromFile("...");   (OCC import, returns volumes)
  Geometry.OCCTargetUnit = "MM";  Mesh.* options;  General.NumThreads
  gmsh <script>.geo -3 -format msh22 -o <out>.msh -nt 1 -v 4
    -3: 3D mesh then exit; -format msh22: MSH 2.2; -o: output file; -nt: threads; -v: verbosity
"""
from __future__ import annotations

import re
import subprocess
import threading
import time
from pathlib import Path
from typing import Callable, Optional

import numpy as np
import psutil

from ... import defaults
from ..elements import GMSH_TO_CCX
from ..msh import read_msh22
from . import MeshRequest, MeshResult, finish_blocks, save_neutral

# Known Gmsh error lines -> short hint for the diagnostic evidence.
KNOWN_ERRORS = [
    (re.compile(r"Could not recover boundary|Invalid boundary mesh|self-intersect", re.I),
     "surface mesh intersects itself: dirty or tiny geometry"),
    (re.compile(r"No elements in volume|0 elements", re.I), "volume produced no elements"),
    (re.compile(r"Could not (read|open|load)|Unknown OpenCASCADE|Could not import", re.I),
     "geometry file could not be read"),
    (re.compile(r"HXT.*(not|only) .*triangles", re.I), "HXT needs a triangle surface mesh"),
]

ALGORITHMS = [(10, "hxt"), (1, "delaunay")]


def kill_tree(pid: int) -> None:
    try:
        p = psutil.Process(pid)
    except psutil.Error:
        return
    for c in p.children(recursive=True) + [p]:
        try:
            c.kill()
        except psutil.Error:
            pass


def run_logged(cmd: list[str], cwd: Path, log_path: Path, timeout_s: float,
               on_line: Callable[[str], None]) -> tuple[Optional[int], bool, list[str]]:
    """Run a process, stream its output to a log and on_line(); kill the tree on timeout.
    Returns (exit code or None, timed_out, last lines)."""
    tail: list[str] = []
    with open(log_path, "a", encoding="utf-8", errors="replace") as log:
        p = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             stdin=subprocess.DEVNULL, text=True, errors="replace",
                             creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))

        def pump():
            for line in p.stdout:
                line = line.rstrip()
                log.write(line + "\n")
                tail.append(line)
                del tail[:-40]
                on_line(line)
        t = threading.Thread(target=pump, daemon=True)
        t.start()
        try:
            p.wait(timeout=timeout_s)
            timed_out = False
        except subprocess.TimeoutExpired:
            kill_tree(p.pid)
            p.wait()
            timed_out = True
        t.join(timeout=5)
        if p.stdout:
            p.stdout.close()
    return (None if timed_out else p.returncode), timed_out, tail


class GmshCliBackend:
    name = "gmsh_cli"

    def __init__(self, exe: Optional[str]):
        self.exe = exe
        self._version: Optional[str] = None

    def available(self) -> bool:
        return bool(self.exe and Path(self.exe).is_file())

    def version(self) -> str:
        if self._version is None:
            if not self.available():
                return "unavailable"
            # Popen + tree kill: on Windows a timed-out subprocess.run can still block on
            # pipes held open by grandchildren.
            try:
                p = subprocess.Popen([self.exe, "-version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                     stdin=subprocess.DEVNULL, text=True,
                                     creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
                try:
                    out, _ = p.communicate(timeout=15)
                except subprocess.TimeoutExpired:
                    kill_tree(p.pid)
                    out = ""
                lines = (out or "").strip().splitlines()
                self._version = lines[-1].strip() if lines else "unknown"
            except OSError:
                self._version = "unknown"
        return self._version

    def script(self, req: MeshRequest, algo: int, optimise: bool = False) -> str:
        geom = Path(req.geometry_file).resolve().as_posix()
        smin = req.size_min if req.size_min else req.size_max * defaults.MESH_SIZE_MIN_FRACTION
        return "\n".join([
            "// generated by asmfea gmsh_cli backend",
            'SetFactory("OpenCASCADE");',
            'Geometry.OCCTargetUnit = "MM";',
            f'v() = ShapeFromFile("{geom}");',
            f"Mesh.MeshSizeMax = {req.size_max:.9g};",
            f"Mesh.MeshSizeMin = {smin:.9g};",
            f"Mesh.MeshSizeFromCurvature = {defaults.MESH_CURVATURE_POINTS};",
            f"Mesh.ElementOrder = {req.order};",
            "Mesh.SecondOrderIncomplete = 1;",
            # a fast run asks Gmsh to untangle its quadratic elements: curving mid-side nodes onto the corner
            # radius of an angled SHS end inverted some (speed investigation)
            "Mesh.HighOrderOptimize = 2;" if optimise or (req.extra or {}).get("gmsh_optimize") else "",
            f"Mesh.Algorithm3D = {algo};",
            "Mesh.MshFileVersion = 2.2;",
            "Mesh.Binary = 0;",
            f"General.NumThreads = {req.threads};",
            "",
        ])

    def mesh(self, req: MeshRequest, on_line: Callable[[str], None] = lambda s: None) -> MeshResult:
        out_dir = Path(req.out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        log_path = out_dir / "gmsh.log"
        if not self.available():
            return MeshResult(False, self.name, error=f"Gmsh executable not found: {self.exe}", log_path=None)
        deadline = time.time() + req.timeout_s
        errors = []
        # each algorithm as it is first; when its quadratic elements come out inverted, again with Gmsh's
        # high-order optimiser, which untangles them (a 297-body weldment: 200 parts inverted; found live)
        already = bool((req.extra or {}).get("gmsh_optimize"))
        tries = [(algo, label, opt) for algo, label in ALGORITHMS for opt in ((True,) if already else (False, True))]
        skip = set()
        for algo, label, optimise in tries:
            if (label, optimise) in skip:
                continue
            remaining = deadline - time.time()
            if remaining <= 1:
                return MeshResult(False, self.name, log_path=log_path, timed_out=True,
                                  error=f"timeout after {req.timeout_s:.0f} s ({'; '.join(errors)})")
            tag = label + ("_opt" if optimise and not already else "")
            geo = out_dir / f"mesh_{tag}.geo"
            msh = out_dir / f"mesh_{tag}.msh"
            geo.write_text(self.script(req, algo, optimise))
            with open(log_path, "a") as lg:
                lg.write(f"--- {self.name} algorithm {label}\n")
            code, timed_out, tail = run_logged(
                [self.exe, str(geo), "-3", "-format", "msh22", "-o", str(msh), "-nt", str(req.threads), "-v", "4"],
                out_dir, log_path, remaining, on_line)
            if timed_out:
                return MeshResult(False, self.name, log_path=log_path, timed_out=True,
                                  error=f"timeout after {req.timeout_s:.0f} s (algorithm {label})")
            err_lines = [l for l in tail if l.startswith("Error")]
            if code != 0 or err_lines or not msh.exists():
                first = err_lines[0] if err_lines else f"exit code {code}"
                hint = next((h for rx, h in KNOWN_ERRORS if rx.search("\n".join(tail))), None)
                errors.append(f"{tag}: {first}" + (f" [{hint}]" if hint else ""))
                skip.add((label, True))           # the optimiser only helps inverted elements
                continue
            try:
                r = self._convert(msh, out_dir, label, log_path)
                if r.quality is not None:
                    r.quality["optimised"] = bool(optimise)
                return r
            except Exception as e:  # unreadable or inverted output: optimise, else the next algorithm
                errors.append(f"{tag}: {e}")
                if "inverted" not in str(e):
                    skip.add((label, True))
        return MeshResult(False, self.name, log_path=log_path, error="; ".join(errors))

    def _convert(self, msh: Path, out_dir: Path, label: str, log_path: Path) -> MeshResult:
        ids, coords, elems = read_msh22(msh)
        blocks = []
        for ty, conn in elems.items():
            if ty in GMSH_TO_CCX:
                etype, perm = GMSH_TO_CCX[ty]
                blocks.append((etype, conn[:, perm]))
        if not blocks:
            raise RuntimeError("no volume elements in the mesh")
        # compact numbering 1..N over the nodes the volume elements use
        used = np.unique(np.concatenate([c.ravel() for _, c in blocks]))
        pos = {int(n): i for i, n in enumerate(ids)}
        X = coords[[pos[int(n)] for n in used]]
        remap = np.zeros(int(used.max()) + 1, dtype=np.int64)
        remap[used] = np.arange(1, len(used) + 1)
        Xp = np.vstack([np.zeros((1, 3)), X])  # row = local id
        blocks, quality = finish_blocks(Xp, [(t, remap[c]) for t, c in blocks])
        if quality["inverted"]:
            # flat tets count too (D86): the same retry (optimised, then the next algorithm) clears them
            raise RuntimeError(f"inverted: {quality['inverted']} elements with a non-positive Jacobian or no volume "
                               f"({quality.get('flat', 0)} flat)")
        out = out_dir / "mesh.npz"
        save_neutral(out, X, blocks)
        quality["algorithm"] = label
        return MeshResult(True, self.name, mesh_file=out, nodes=len(X), elements=sum(len(c) for _, c in blocks),
                          quality=quality, log_path=log_path, surface_tolerance=1e-3)
